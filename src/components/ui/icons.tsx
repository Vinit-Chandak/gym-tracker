type IconScale = "control" | "navigation" | "row" | "feature";
export type AppIconProps = Omit<IconProps, "size" | "weight" | "strokeWidth"> & {
  /** Glyph dimensions only; the surrounding control owns its hit target. */
  scale?: IconScale;
};
export type AppIcon = ComponentType<AppIconProps>;

/**
 * One family, one stroke: Phosphor's regular weight everywhere, drawn like the rest of the
 * sheet's line work. Context-free imports work in both server and client components, and
 * individual modules mean development never has to compile the entire icon catalog.
 */
function glyph(Icon: PhosphorIcon): AppIcon {
  return function Glyph({ scale = "control", className, ...props }: AppIconProps) {
    return (
      <Icon
        aria-hidden={
          props.alt || props["aria-label"] || props["aria-labelledby"] ? undefined : true
        }
        focusable="false"
        {...props}
        weight="regular"
        className={cn("app-icon", className)}
        data-icon-scale={scale}
      />
    );
  };
}

