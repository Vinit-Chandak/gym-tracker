import type {
  ExerciseCategory,
  ExerciseModality,
  LoadPortability,
  MuscleGroup,
  PrescriptionType,
} from "../../../domain/types";

export type ExerciseSeed = {
  slug: string;
  name: string;
  category: ExerciseCategory;
  modality: ExerciseModality;
  movementPattern: string;
  primaryMuscles: MuscleGroup[];
  secondaryMuscles?: MuscleGroup[];
  loadPortability: LoadPortability;
  requiresEquipment?: boolean;
  /**
   * What one set of this movement counts. Omitted means reps, which is most of the library;
   * a plank counts seconds and a carry counts metres, and asking either for reps is asking a
   * question the movement has no answer to.
   */
  measure?: PrescriptionType;
  defaultRepMin?: number;
  defaultRepMax?: number;
  /** Seconds, for `duration` movements. */
  defaultDurationMin?: number;
  defaultDurationMax?: number;
  /** Metres, for `distance` movements. */
  defaultDistanceMin?: number;
  defaultDistanceMax?: number;
  defaultRir?: number;
  /**
   * What reps in reserve means here, when the general explanation would mislead. A deadlift's
   * two RIR is a different instruction from a carry's or a plank's.
   */
  rirNote?: string;
  defaultRestSeconds?: number;
  /** kg; null when the machine decides. */
  defaultLoadIncrement?: number | null;
  formNotes?: string;
  formUrl?: string;
  isActive?: boolean;
  /** Equipment type slugs in preference order. */
  equipment: string[];
};

