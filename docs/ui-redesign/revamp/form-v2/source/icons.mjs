export const STROKE = { sw: 2, cap: "round", join: "round" };

export function glyph(name, opts = {}) {
  const g = GLYPHS[name];
  if (!g) throw new Error(`no glyph ${name}`);
  return svg(g, { ...STROKE, ...opts });
}
export const hasGlyph = (name) => !!GLYPHS[name];

